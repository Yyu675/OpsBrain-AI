package com.devops.agent.domain.alert;

/**
 * 告警分类（AIOps 业界共识：业务/技术/安全/因果四类告警的诊断策略本质不同）。
 *
 * <h3>为什么要分类</h3>
 * 此前所有告警都走同一套「技术指标+日志」诊断——业务性告警（如工单积压）没有
 * 技术指标可查，AI 只能硬往技术故障上靠（实测：工单积压被诊断为 SQL 注入）。
 * 分类后按类型给 AI 不同的诊断上下文：
 * <ul>
 *   <li>{@link #TECHNICAL}：CPU/内存/Pod/DB 等——指标+日志+变更+知识（现有行为）；</li>
 *   <li>{@link #BUSINESS}：积压/SLA/转化等业务流程——业务上下文（工单分布/负责人/SLA 状态），
 *       不再硬找技术指标；</li>
 *   <li>{@link #SECURITY}：攻击/异常流量——安全上下文（源/攻击模式/影响面）；</li>
 *   <li>{@link #CAUSAL}：可预测的资源耗尽（磁盘将满/证书将过期）——趋势预测（剩余时间/增长率）。</li>
 * </ul>
 *
 * <h3>可扩展</h3>
 * 新增告警类型 = 加一个枚举值 + 在 {@code AlertKindClassifier} 加一条分类规则 +
 * 在诊断策略处加一类上下文。分类与诊断解耦，互不动对方代码。
 */
public enum AlertKind {

    /** 技术性故障（默认）：CPU/内存/Pod/DB/网络等基础设施/应用层故障。 */
    TECHNICAL,

    /** 业务性预警：工单积压、SLA 将违约、转化率下降等业务流程指标。 */
    BUSINESS,

    /** 安全型告警：攻击、异常流量、注入尝试等。 */
    SECURITY,

    /** 因果型预警：可预测的资源耗尽（磁盘将满、证书将过期、配额将用尽）。 */
    CAUSAL
}
